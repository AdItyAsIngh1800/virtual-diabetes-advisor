def _reject_mutation(_mapper: Mapper[Base], _connection: Connection, target: Base) -> None:
    """ORM guard: refuse to flush an UPDATE or DELETE of an append-only row.

    Args:
        _mapper: The mapper of the row's class (unused).
        _connection: The connection the flush runs on (unused).
        target: The row being updated or deleted.

    Raises:
        AuditLogImmutableError: Always.
    """
    raise AuditLogImmutableError(f"{type(target).__tablename__} is append-only")


