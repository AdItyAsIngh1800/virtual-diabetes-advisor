"""SQLAlchemy 2.0 models mirroring the Supabase schema in ``app/db/migrations``.

The SQL migrations are the source of truth: never call ``Base.metadata.create_all``
against Supabase. These models exist so services and jobs get typed rows. Every
``Literal`` below mirrors a ``CHECK (... in (...))`` list in the migrations;
``tests/test_db_models.py`` fails if the two drift apart.

Text columns with a fixed value set are mapped through :func:`_choice`, a non-native
``Enum`` that stores plain TEXT (matching the migration) but rejects unknown values in
Python before they reach the database.

Row Level Security (``0002_rls.sql``) does not apply to the backend: it connects with
the service role / database owner. It applies to dashboard clients that read through
Supabase with a user JWT.
"""

