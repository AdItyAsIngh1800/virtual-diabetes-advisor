def _choice(literal: object) -> Enum:
    """Build a TEXT-backed enum type from a ``Literal`` alias.

    Args:
        literal: A ``typing.Literal`` alias such as :data:`UserRole`.

    Returns:
        A non-native :class:`sqlalchemy.Enum` that validates values in Python and
        emits no CHECK constraint (the migration already defines it).
    """
    return Enum(
        *get_args(literal),
        native_enum=False,
        create_constraint=False,
        validate_strings=True,
        length=None,
    )


def _uuid_pk() -> Mapped[uuid.UUID]:
    """Return a UUID primary-key column generated by Postgres.

    Returns:
        A mapped column defaulting to ``gen_random_uuid()``.
    """
    return mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid()
    )


def _created_at() -> Mapped[datetime]:
    """Return a ``created_at timestamptz not null default now()`` column.

    Returns:
        The mapped column.
    """
    return mapped_column(_TZ, nullable=False, server_default=func.now())


def _updated_at() -> Mapped[datetime]:
    """Return an ``updated_at`` column maintained by the ``set_updated_at`` trigger.

    Returns:
        The mapped column; the ORM reloads it after each flush.
    """
    return mapped_column(_TZ, nullable=False, server_default=func.now(), server_onupdate=func.now())


